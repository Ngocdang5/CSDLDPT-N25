CREATE TABLE audio (
    audio_id    INTEGER PRIMARY KEY,
    file_name   VARCHAR(255) NOT NULL UNIQUE,
    file_path   VARCHAR(512) NOT NULL,
    format      VARCHAR(10),
    genre       VARCHAR(50),
    instrument  VARCHAR(100),
    duration    DOUBLE PRECISION,
    sample_rate INTEGER,
    channels    INTEGER,
    split       VARCHAR(10) NOT NULL CHECK (split IN ('database', 'test'))
);

